-- Code vision (lua/lang/lens.lua): usages of functions, types and globals;
-- in C++ also ↓ subclasses of a class and overrides of a method. `gd` goes to
-- the declaration (the prototype in a header), `gi` to implementations or,
-- with none (always in C), to the definition (the body). On a prototype or a
-- body clangd answers both with the other one.
local Kind = vim.lsp.protocol.SymbolKind

local USAGE_KINDS = {
  [Kind.Function] = true, [Kind.Method] = true,
  [Kind.Class] = true, [Kind.Struct] = true, [Kind.Enum] = true, [Kind.Interface] = true,
  [Kind.Variable] = true, [Kind.Constant] = true,
}

M.lens = {
  client = "clangd",
  queries = function(sym, parent, bufnr)
    local queries = {}
    if USAGE_KINDS[sym.kind] and not (parent == nil and sym.name == "main") then
      table.insert(queries, "usages")
    end
    if vim.bo[bufnr].filetype == "cpp"
      and (sym.kind == Kind.Class or sym.kind == Kind.Struct or sym.kind == Kind.Method) then
      table.insert(queries, "down")
    end
    return queries
  end,
  fallback = "textDocument/definition",
}

local function map(bufnr, mode, lhs, rhs, desc)
  vim.keymap.set(mode, lhs, rhs, { buffer = bufnr, silent = true, desc = desc })
end

-- cppman — cppreference manpage lookup in a floating window.
-- Requires the `cppman` CLI on $PATH (`brew install cppman`).
local function cppman_open_float(symbol, lines)
  local buf = vim.api.nvim_create_buf(false, true)
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines)
  vim.bo[buf].modifiable = false
  vim.bo[buf].buftype    = "nofile"
  vim.bo[buf].bufhidden  = "wipe"
  vim.bo[buf].filetype   = "man"

  -- Layer C++ treesitter highlighting on top of the `man` filetype: section
  -- headers (NAME, SYNOPSIS, …) stay highlighted by man.vim, while code
  -- blocks pick up keyword/type/operator colors from the cpp parser.
  pcall(vim.treesitter.start, buf, "cpp")

  local width  = math.floor(vim.o.columns * 0.8)
  local height = math.floor(vim.o.lines * 0.75)
  local row    = math.floor((vim.o.lines - height) / 2)
  local col    = math.floor((vim.o.columns - width) / 2)

  local win = vim.api.nvim_open_win(buf, true, {
    relative  = "editor",
    width     = width,
    height    = height,
    row       = row,
    col       = col,
    style     = "minimal",
    border    = "rounded",
    title     = " cppman: " .. symbol .. " ",
    title_pos = "center",
  })
  vim.wo[win].wrap       = false
  vim.wo[win].cursorline = true

  local function close()
    if vim.api.nvim_win_is_valid(win) then vim.api.nvim_win_close(win, true) end
  end
  local opts = { buffer = buf, nowait = true, silent = true }
  vim.keymap.set("n", "q",     close, opts)
  vim.keymap.set("n", "<Esc>", close, opts)
  vim.keymap.set("n", "<C-c>", close, opts)
end

-- In-memory cache: { [symbol] = { lines... } }. Survives for the lifetime of
-- the Neovim session, layered on top of cppman's own ~/.cache/cppman disk
-- cache. Wipe with `:lua require("lang.cpp")._reset_cppman_cache()` if needed.
local cppman_cache = {}

function M._reset_cppman_cache() cppman_cache = {} end

local function cppman_lookup(symbol)
  if not symbol or symbol == "" then
    vim.notify("cppman: no symbol under cursor", vim.log.levels.WARN)
    return
  end
  if vim.fn.executable("cppman") == 0 then
    vim.notify("cppman: CLI not found — `brew install cppman`", vim.log.levels.ERROR)
    return
  end
  if cppman_cache[symbol] then
    cppman_open_float(symbol, cppman_cache[symbol])
    return
  end
  vim.system(
    { "cppman", symbol },
    { text = true, env = { MANPAGER = "cat", PAGER = "cat", MANWIDTH = tostring(math.max(80, math.floor(vim.o.columns * 0.8) - 4)) } },
    vim.schedule_wrap(function(obj)
      local out = obj.stdout or ""
      if obj.code ~= 0 or out == "" then
        vim.notify("cppman: no entry for `" .. symbol .. "`", vim.log.levels.INFO)
        return
      end
      local lines = vim.split(out, "\n", { plain = true, trimempty = false })
      cppman_cache[symbol] = lines
      cppman_open_float(symbol, lines)
    end)
  )
end

local function cppman_prompt()
  vim.ui.input({ prompt = "cppman: ", default = vim.fn.expand("<cword>") }, function(input)
    if input then cppman_lookup(input) end
  end)
end

local function on_clangd_attach(client, bufnr)
  -- Header/source switch.
  map(bufnr, "n", "gh", function() switch_source_header(bufnr) end, "C++: switch source/header")
  map(bufnr, "n", "<F4>", function() switch_source_header(bufnr) end, "C++: switch source/header")

  -- Code vision, as in Go. `gd` / `gi` pressed again where they landed come
  -- back.
  local lens = require("lang.lens")
  lens.attach(bufnr, M.lens)
  map(bufnr, "n", "gd", lens.toggle("gd", function(done) lens.declaration(bufnr, done) end),
    "C++: declaration (prototype); again: back")
  map(bufnr, "n", "gi", lens.toggle("gi", function(done) lens.open(bufnr, done) end),
    "C++: implementations, else definition (body); again: back")
  map(bufnr, "n", "gu", function() lens.usages(bufnr) end, "C++: usages")

  -- cppman lookup.
  map(bufnr, "n", "gK",         function() cppman_lookup(vim.fn.expand("<cword>")) end, "C++: cppman lookup (word)")
  map(bufnr, "n", "<leader>cM", cppman_prompt,                                          "C++: cppman lookup (prompt)")

  -- Hierarchies.
  map(bufnr, "n", "<leader>ch", vim.lsp.buf.incoming_calls,  "C++: incoming calls")
  map(bufnr, "n", "<leader>cH", vim.lsp.buf.outgoing_calls,  "C++: outgoing calls")
  map(bufnr, "n", "<leader>ct", function() run_type_hierarchy(bufnr, "subtypes") end,
    "C++: subtypes (children)")
  map(bufnr, "n", "<leader>cT", function() run_type_hierarchy(bufnr, "supertypes") end,
    "C++: supertypes (parents)")

  -- Inlay hints — OFF by default per spec.
  if vim.lsp.inlay_hint then
    vim.lsp.inlay_hint.enable(false, { bufnr = bufnr })
  end
  map(bufnr, "n", "<leader>ci", function() toggle_inlay_hints(bufnr) end, "C++: toggle inlay hints")

  -- Formatting.
  map(bufnr, "n", "<leader>cf", function() format_buffer(bufnr) end,           "C++: format buffer")
  map(bufnr, "x", "<leader>cf", function() format_buffer(bufnr) end,           "C++: format selection")
  map(bufnr, "n", "<leader>cF", function() M.toggle_format_on_save(bufnr) end, "C++: toggle format-on-save")

  -- clangd_extensions commands.
  map(bufnr, "n", "<leader>cs", "<cmd>ClangdSymbolInfo<cr>",  "C++: symbol info")
  map(bufnr, "n", "<leader>cm", "<cmd>ClangdMemoryUsage<cr>", "C++: clangd memory usage")
  map(bufnr, "n", "<leader>cA", "<cmd>ClangdAST<cr>",         "C++: clangd AST")

  -- Neotest (buffer-local so we don't pollute other languages globally).
  local ok_neotest, neotest = pcall(require, "neotest")
  if ok_neotest then
    map(bufnr, "n", "<leader>tt", function() neotest.run.run() end,                             "C++: test nearest")
    map(bufnr, "n", "<leader>tf", function() neotest.run.run(vim.fn.expand("%")) end,           "C++: test file")
    map(bufnr, "n", "<leader>tT", function() neotest.run.run(vim.fn.getcwd()) end,              "C++: test all")
    map(bufnr, "n", "<leader>td", function() neotest.run.run({ strategy = "dap" }) end,         "C++: debug nearest test")
    map(bufnr, "n", "<leader>ts", function() neotest.summary.toggle() end,                      "C++: test summary")
    map(bufnr, "n", "<leader>to", function() neotest.output.open({ enter = true }) end,         "C++: test output")
    map(bufnr, "n", "<leader>tx", function() neotest.run.stop() end,                            "C++: stop test")
  end
end

function M.setup_autocmds()
  local group = vim.api.nvim_create_augroup("CppLang", { clear = true })

  vim.api.nvim_create_autocmd("LspAttach", {
    group = group,
    callback = function(args)
      local client = vim.lsp.get_client_by_id(args.data.client_id)
      if not client or client.name ~= "clangd" then return end
      on_clangd_attach(client, args.buf)
    end,
  })

  vim.api.nvim_create_autocmd("BufWritePre", {
    group = group,
    pattern = M.format_patterns,
    callback = function(args)
      if not M.should_format_on_save(args.buf) then return end
      local ok, conform = pcall(require, "conform")
      if not ok then return end
      conform.format({ bufnr = args.buf, async = false, timeout_ms = 3000, lsp_format = "never" })
    end,
  })

  -- A new source file or changed flags: refresh the generated database of
  -- the running clangd that owns the file.
  vim.api.nvim_create_autocmd("BufWritePost", {
    group = group,
    callback = function(args)
      if not (is_source(args.file) or vim.fs.basename(args.file) == "compile_flags.txt") then return end
      local file = vim.fs.normalize(vim.fn.fnamemodify(args.file, ":p"))
      for _, client in ipairs(vim.lsp.get_clients({ name = "clangd" })) do
        if client.root_dir and vim.startswith(file, client.root_dir .. "/") then
          M.sync_compile_commands(client.root_dir)
        end
      end
    end,
  })

  -- Register dap configurations the first time a C/C++ file is opened.
  -- nvim-dap is owned by lua/plugins/debug.lua; we only inject configs.
  local dap_registered = false
  vim.api.nvim_create_autocmd("FileType", {
    group = group,
    pattern = { "c", "cpp" },
    callback = function()
      if dap_registered then return end
      dap_registered = true
      M.setup_dap()
    end,
  })
end

