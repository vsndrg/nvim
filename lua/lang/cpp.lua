-- C/C++ language orchestration: clangd server config, buffer keymaps,
-- format-on-save with .clang-format detection, inlay hints, switch header/source,
-- and CMake/neotest/dap wiring helpers.
--
-- Public entrypoints:
--   require("lang.cpp").setup()                         -- one-shot startup setup
--   require("lang.cpp").setup_cmake_keymaps()           -- called from cmake-tools config
--   require("lang.cpp").setup_dap()                     -- called from dap config
--   require("lang.cpp").register_neotest_adapters()     -- returns adapter list

local M = {}

M.filetypes = { "c", "cpp", "objc", "objcpp", "cuda" }

M.format_patterns = {
  "*.c", "*.cc", "*.cpp", "*.cxx", "*.c++",
  "*.h", "*.hh", "*.hpp", "*.hxx", "*.h++",
  "*.m", "*.mm", "*.cu",
}

-- Resolve LLVM tooling paths; fall back to system binaries.
local function llvm_or_system(name)
  local llvm = "/opt/homebrew/opt/llvm/bin/" .. name
  if vim.fn.executable(llvm) == 1 then return llvm end
  return name
end

function M.clangd_path()   return llvm_or_system("clangd") end
function M.clang_format()  return llvm_or_system("clang-format") end
function M.clang_tidy()    return llvm_or_system("clang-tidy") end

-- Build clangd capabilities. Pulls blink.cmp's enriched capabilities if present.
-- snippetSupport=true so clangd returns function signatures with placeholders
-- ($1, $2, …) for cursor jumps; luasnip handles expansion via blink.cmp.
local function clangd_capabilities()
  local caps = vim.lsp.protocol.make_client_capabilities()
  local ok, blink = pcall(require, "blink.cmp")
  if ok and blink.get_lsp_capabilities then
    caps = blink.get_lsp_capabilities(caps)
  end
  caps.textDocument.completion.completionItem.snippetSupport = true
  caps.textDocument.completion.completionItem.resolveSupport = {
    properties = { "documentation", "detail", "additionalTextEdits" },
  }
  caps.offsetEncoding = { "utf-16" }
  caps.textDocument.semanticTokens = {
    dynamicRegistration = false,
    requests = { range = false, full = { delta = true } },
    tokenTypes = {
      "namespace", "type", "class", "enum", "interface",
      "struct", "typeParameter", "parameter", "variable",
      "property", "enumMember", "event", "function", "method",
      "macro", "keyword", "modifier", "comment", "string",
      "number", "regexp", "operator", "decorator",
    },
    tokenModifiers = {
      "declaration", "definition", "readonly", "static",
      "deprecated", "abstract", "async", "modification",
      "documentation", "defaultLibrary",
    },
    formats = { "relative" },
    overlappingTokenSupport = true,
    multilineTokenSupport = true,
  }
  return caps
end

-- User-level fallback .clangd config for standalone files outside CMake/compile_commands.json.
-- Project-local .clangd or compile_commands.json take precedence over this file.
local function ensure_user_clangd_config()
  -- clangd's user config dir is OS-specific: XDG (~/.config) on Linux,
  -- ~/Library/Preferences on macOS. Writing to ~/.config on macOS produces
  -- a file clangd silently never reads.
  local cfg_dir = vim.fn.has("mac") == 1
    and vim.fn.expand("~/Library/Preferences/clangd")
    or vim.fn.expand("~/.config/clangd")
  local cfg_file = cfg_dir .. "/config.yaml"
  if vim.fn.filereadable(cfg_file) == 1 then return end
  vim.fn.mkdir(cfg_dir, "p")
  local content = table.concat({
    "# User-level clangd defaults — applied to files outside any project.",
    "# Generated by lua/lang/cpp.lua. Edit freely; this file is not regenerated.",
    "CompileFlags:",
    "  Add:",
    "    - -Wall",
    "    - -Wextra",
    "Diagnostics:",
    "  UnusedIncludes: Strict",
    "  MissingIncludes: Strict",
    "Completion:",
    "  AllScopes: No",
    "---",
    "# C++ only: C keeps the project's -std, or clang's default (gnu17).",
    "If:",
    "  PathMatch: .*\\.(cc|cpp|cxx|c\\+\\+|hh|hpp|hxx|h\\+\\+|ipp|tpp)",
    "CompileFlags:",
    "  Compiler: clang++",
    "  Add:",
    "    - -std=c++23",
    "",
  }, "\n")
  local f = io.open(cfg_file, "w")
  if f then
    f:write(content)
    f:close()
  end
end

-- ─────────────────────────────────────────────────────────────────────────────
-- Compilation database for compile_flags.txt projects
-- ─────────────────────────────────────────────────────────────────────────────
-- compile_flags.txt gives flags but no file list, so clangd indexes nothing in
-- the background and only knows what the open files define: `gd` on a
-- prototype in a header stays put until the .c with its body is opened. Such
-- projects get a compile_commands.json built from those flags and every
-- source file. It lives in nvim's cache, clangd's index next to it, so nothing
-- is written into the project.

local SOURCE_EXT = { c = true, cc = true, cpp = true, cxx = true, ["c++"] = true, m = true, mm = true, cu = true }

local function is_source(path)
  return SOURCE_EXT[path:match("%.([^./]+)$") or ""] == true
end

-- Tracked and untracked-but-not-ignored sources of a git repo, every source
-- under `root` otherwise.
local function source_files(root)
  local git = vim.system({ "git", "-C", root, "ls-files", "-co", "--exclude-standard" }, { text = true }):wait()
  local files = {}
  if git.code == 0 then
    for _, rel in ipairs(vim.split(git.stdout, "\n", { trimempty = true })) do
      if is_source(rel) then table.insert(files, vim.fs.joinpath(root, rel)) end
    end
  else
    files = vim.fs.find(is_source, { path = root, type = "file", limit = math.huge })
  end
  table.sort(files)
  return files
end

-- (Re)writes the database of `root` when the project needs one; returns the
-- directory holding it, or nil.
function M.sync_compile_commands(root)
  if not root then return nil end
  for _, own in ipairs({ "compile_commands.json", "build/compile_commands.json" }) do
    if vim.uv.fs_stat(vim.fs.joinpath(root, own)) then return nil end
  end
  local flags = vim.F.npcall(vim.fn.readfile, vim.fs.joinpath(root, "compile_flags.txt"))
  if not flags then return nil end
  flags = vim.tbl_filter(function(flag) return flag ~= "" end, flags)

  local entries = {}
  for _, file in ipairs(source_files(root)) do
    local args = vim.list_extend({ "clang" }, flags)
    table.insert(args, file)
    table.insert(entries, { directory = root, file = file, arguments = args })
  end

  local dir = vim.fs.joinpath(vim.fn.stdpath("cache"), "clangd-cdb", (root:gsub("/", "%%")))
  local path = vim.fs.joinpath(dir, "compile_commands.json")
  local text = vim.json.encode(entries)
  -- An unchanged file keeps its mtime, so clangd does not reload it.
  if table.concat(vim.F.npcall(vim.fn.readfile, path, "b") or {}, "\n") ~= text then
    vim.fn.mkdir(dir, "p")
    vim.fn.writefile({ text }, path, "b")
  end
  return dir
end

function M.setup_server()
  ensure_user_clangd_config()

  vim.lsp.config("clangd", {
    cmd = {
      M.clangd_path(),
      "--background-index",
      "--clang-tidy",
      "--completion-style=bundled",
      "--function-arg-placeholders=true",
      "--header-insertion=never",
      "--fallback-style=LLVM",
      "--pch-storage=memory",
      "--cross-file-rename",
      "--enable-config",
      "--limit-results=100",
      "-j=4",
    },
    -- lspconfig's flat list ranks .clangd first, so ~/.clangd made the whole
    -- home directory the root of every project under it. Equal priority: the
    -- nearest directory with any project marker wins, .git only without one.
    root_markers = {
      { ".clangd", ".clang-tidy", ".clang-format", "compile_commands.json", "compile_flags.txt", "configure.ac" },
      ".git",
    },
    capabilities = clangd_capabilities(),
    init_options = {
      usePlaceholders = true,
      completeUnimported = false,
      clangdFileStatus = true,
    },
    before_init = function(params, config)
      local dir = M.sync_compile_commands(config.root_dir)
      if dir then
        -- A copy: init_options is one table shared by every clangd instance.
        params.initializationOptions = vim.tbl_extend("force", params.initializationOptions or {},
          { compilationDatabasePath = dir })
      end
    end,
  })
  vim.lsp.enable("clangd")
end

-- ─────────────────────────────────────────────────────────────────────────────
-- Format-on-save state
-- ─────────────────────────────────────────────────────────────────────────────
-- Per-buffer override: vim.b[buf].cpp_format_on_save
--   nil   → auto: enabled iff .clang-format reachable upward from the file
--   true  → forced on
--   false → forced off

local function find_upward(name, from)
  local found = vim.fs.find(name, { upward = true, path = from, type = "file" })
  return found and found[1] or nil
end

local function has_clang_format(bufnr)
  local fname = vim.api.nvim_buf_get_name(bufnr or 0)
  if fname == "" then return false end
  return find_upward(".clang-format", vim.fs.dirname(fname)) ~= nil
end

function M.should_format_on_save(bufnr)
  bufnr = bufnr or 0
  local override = vim.b[bufnr].cpp_format_on_save
  if override ~= nil then return override end
  return has_clang_format(bufnr)
end

function M.toggle_format_on_save(bufnr)
  bufnr = bufnr or 0
  local effective = M.should_format_on_save(bufnr)
  vim.b[bufnr].cpp_format_on_save = not effective
  vim.notify(
    ("clang-format on save: %s%s"):format(
      vim.b[bufnr].cpp_format_on_save and "ON" or "OFF",
      has_clang_format(bufnr) and "" or " (no .clang-format found)"
    ),
    vim.log.levels.INFO
  )
end

